package F_JavaSwitchStatement6;

public class A_SwitchStatementImplementation {

	  public static void main(String[] args) {
		  
		  char grade = 'D';
		  
		  switch(grade) {
		  
		  		case 'A':
		  			System.out.println("Perfect");
		  		break;
		  		case 'B':
		  			System.out.println("Very Good");
		  		break;
		  		case 'C':
		  			System.out.println("Good");
		  		break;
		  }
	  }
}
