package K_JavaMethods11;

public class A_MethodsImplementation {

	public static void main(String[] args) {

		sayHello();
		sayHi();
		
	}
	
	// This method says Hi
	static void sayHi() {
		System.out.println("Hi");
	}
	// This method says Hello
	static void sayHello() {
		System.out.println("Hello");
	}
	
}
