package L2_JavaMathematics12;

public class arithmetic {
	
	public int add(int num1, int num2) {
		return num1 + num2;
	}

	public int multiply(int num1, int num2) {
		return num1 * num2;
	}
	
	public int divide(int num1, int num2) {
		return num1 / num2;
	}
	
	public int subtract(int num1, int num2) {
		return num1 - num2;
	}
	
	// Non access modifier, hindi na kailangan ng class instantiate basta imported un package
	public static int add2(int num1, int num2) {
		return num1 + num2;
	}

	public static int multiply2(int num1, int num2) {
		return num1 * num2;
	}
	
	public static int divide2(int num1, int num2) {
		return num1 / num2;
	}
	
	public static int subtract2(int num1, int num2) {
		return num1 - num2;
	}
}
